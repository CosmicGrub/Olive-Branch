// Reference (Node) implementation of the PAKE the pairing protocol uses: a CPace-style balanced PAKE over
// X25519 (generator from the password by hash + Elligator2, one DH each way, key confirmation).
//
// HONEST STATUS. This is CUSTOM cryptographic code (the Elligator2 map and the transcript layout), written
// to follow the STRUCTURE of draft-irtf-cfrg-cpace (CPace255 with SHA-512). It is NOT byte-compatible with the
// draft and has NOT been checked against the draft's official test vectors. Its only cross-check is this
// second implementation: the Dart one (client/lib/cpace.dart) must agree with it byte for byte
// (client/test/vectors/pake_vectors.json, generated by tools/gen-pake-vectors.mjs). It needs an external
// cryptographic review before real families rely on it (spec section 6.1, decision D2).
import { createHash, createHmac, createPrivateKey, createPublicKey, diffieHellman } from 'node:crypto';

export const DSI = 'OliveCPace255';
const P = (1n << 255n) - 19n;
const A = 486662n;

const mod = (a) => ((a % P) + P) % P;
const pow = (b, e) => { let r = 1n; b = mod(b); while (e > 0n) { if (e & 1n) r = mod(r * b); b = mod(b * b); e >>= 1n; } return r; };
const inv = (a) => pow(a, P - 2n);
const leToBig = (buf) => { let r = 0n; for (let i = buf.length - 1; i >= 0; i--) r = (r << 8n) | BigInt(buf[i]); return r; };
const bigToLe32 = (n) => { const o = Buffer.alloc(32); for (let i = 0; i < 32; i++) { o[i] = Number(n & 255n); n >>= 8n; } return o; };

export const lv = (b) => {
  b = Buffer.from(b);
  const len = []; let n = b.length;
  do { let byte = n & 0x7f; n >>= 7; if (n) byte |= 0x80; len.push(byte); } while (n);
  return Buffer.concat([Buffer.from(len), b]);
};
export const sha512 = (...p) => createHash('sha512').update(Buffer.concat(p.map(Buffer.from))).digest();

export function elligator2(u32) {
  const masked = Buffer.from(u32); masked[31] &= 0x7f;
  const u = mod(leToBig(masked));
  const den = mod(1n + 2n * u * u);
  const w = den === 0n ? mod(-A) : mod(-A * inv(den));
  const v = mod(w * w * w + A * w * w + w);
  const square = v === 0n || pow(v, (P - 1n) / 2n) === 1n;
  return bigToLe32(square ? w : mod(-A - w));
}

export function generator(prs, sid, ci) {
  const dsi = lv(Buffer.from(DSI)), p = lv(prs);
  const zpad = Math.max(0, 128 - 1 - p.length - dsi.length);
  const gs = Buffer.concat([dsi, p, Buffer.alloc(zpad), lv(ci), lv(sid)]);
  return elligator2(sha512(gs).subarray(0, 32));
}

const PKCS8 = Buffer.from('302e020100300506032b656e04220420', 'hex');
const SPKI = Buffer.from('302a300506032b656e032100', 'hex');
export function x25519(seed32, u32) {
  const priv = createPrivateKey({ key: Buffer.concat([PKCS8, seed32]), format: 'der', type: 'pkcs8' });
  const pub = createPublicKey({ key: Buffer.concat([SPKI, u32]), format: 'der', type: 'spki' });
  const out = diffieHellman({ privateKey: priv, publicKey: pub });
  if (out.every((b) => b === 0)) throw new Error('low order');
  return Buffer.from(out);
}

export const share = (seed, g) => x25519(seed, g);

export function isk(sid, K, yc, ya) {
  return sha512(lv(Buffer.from(DSI + '_ISK')), lv(sid), lv(K), lv(yc), lv(ya));
}
const kdf = (key, label) => sha512(lv(Buffer.from(label)), lv(key)).subarray(0, 32);
export const transcript = (yc, ya, ci, sid) => Buffer.concat([lv(yc), lv(ya), lv(ci), lv(sid)]);
export const confirmTag = (iskBytes, role, tr) =>
  createHmac('sha256', kdf(iskBytes, 'confirm')).update(Buffer.concat([lv(Buffer.from(role)), tr])).digest();
export const sasBytes = (iskBytes) => kdf(iskBytes, 'sas').subarray(0, 2);
export const channelKey = (iskBytes) => kdf(iskBytes, 'channel');

export function run({ prsC, prsA, sid, ci, yc, ya }) {
  const gC = generator(prsC, sid, ci), gA = generator(prsA, sid, ci);
  const Yc = share(yc, gC), Ya = share(ya, gA);
  const Kc = x25519(yc, Ya), Ka = x25519(ya, Yc);
  const iskC = isk(sid, Kc, Yc, Ya), iskA = isk(sid, Ka, Yc, Ya);
  const tr = transcript(Yc, Ya, ci, sid);
  return { gC, gA, Yc, Ya, iskC, iskA, tagC: confirmTag(iskC, 'C', tr), tagA: confirmTag(iskA, 'A', tr), sas: sasBytes(iskC) };
}
